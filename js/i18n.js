for (const l of ["en", "fr"]) Object.assign(DICT[l], PAGES[l], HELP[l]);

function initial() {
  const p = new URLSearchParams(location.search).get("lang");
  if (p === "en" || p === "fr") return p;
  try {
    const s = localStorage.getItem("lm-lang");
    if (s === "en" || s === "fr") return s;
  } catch { /* storage unavailable */ }
  return "en";
}

let lang = initial();
document.documentElement.lang = lang;

export const getLang = () => lang;

export function setLang(l) {
  lang = l;
  try { localStorage.setItem("lm-lang", l); } catch { /* ignore */ }
  document.documentElement.lang = l;
}

export function t(key, vars = {}) {
  return tl(lang, key, vars);
}

// Translation in an explicit language (used to prebuild texts in both languages).
export function tl(l, key, vars = {}) {
  let s = DICT[l]?.[key] ?? DICT.en[key] ?? key;
  for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, () => String(v));
  return s;
}

export function applyStatic(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  root.querySelectorAll("[data-i18n-aria]").forEach((el) => { el.setAttribute("aria-label", t(el.dataset.i18nAria)); });
  root.querySelectorAll("[data-lang]").forEach((b) => b.setAttribute("aria-pressed", String(b.dataset.lang === lang)));
}
